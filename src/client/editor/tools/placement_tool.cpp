// The geometry half is a manually maintained list.
// The entity half comes from placeable_entity_types(), which is generated by the .def.
enum class placeable_geometry_t
{
  Box,
  Asset_Mesh,
};

struct placeable_t
{
  const char* label = "INVALID";
  bool is_geometry;
  placeable_geometry_t geometry;     // meaningful when is_geometry
  entities::entity_type entity_type; // meaningful otherwise
};

static const std::vector<placeable_t> &placeables()
{
  static const std::vector<placeable_t> table = [] {
    std::vector<placeable_t> result = {
        {"BOX", true, placeable_geometry_t::Box, entities::entity_type::Invalid},
        {"STATIC_MESH", true, placeable_geometry_t::Asset_Mesh, entities::entity_type::Invalid},
    };

    for (entities::entity_type type : entities::placeable_entity_types())
      result.push_back({entities::entity_info(type).display_name, false,
                        placeable_geometry_t::Box, type});

    return result;
  }();
  return table;
}

int Placement_Tool::get_index_of_placeable(const std::string &label)
{
  const auto &table = placeables();
  for (int idx = 0; idx < (int)table.size(); ++idx)
  {
    if (table[idx].label == label)
      return idx;
  }
  return INVALID_PLACEABLE_IDX;
}

void Placement_Tool::on_enable(editor_context_t& ctx)
{
  assert(ctx.map);
  cursor_is_currently_over_surface = false;

  if (!geometry_to_place && !entity_to_place) select_placeable(get_index_of_placeable("BOX"));

}

void Placement_Tool::on_disable(editor_context_t& ctx) { cursor_is_currently_over_surface = false; }

void Placement_Tool::on_update(editor_context_t& ctx,
                               const viewport_state_t &view, float /*dt*/)
{
  const std::optional<linalg::vec3> point = try_pick_placement_point(ctx, view);
  cursor_is_currently_over_surface = point.has_value();
  if (point)
  {
    ghost_position = *point;
  }
}

void Placement_Tool::on_mouse_down(editor_context_t& ctx,
                                   const input::mouse_event_t& e)
{
  if (e.button != input::mouse_button_t::Left || !cursor_is_currently_over_surface) return;

  if (geometry_to_place)
  {
    shared::mesh_geometry_t placed = *geometry_to_place;
    shared::set_position(
        placed, compute_geometry_placement_center(placed, ghost_position,
                                                  ctx.grid ? ctx.grid->step() : 0.0f));

    const shared::entity_uid_t uid = ctx.map->add_geometry(placed);

    transaction_t transaction;
    transaction.add_geometry_created(uid, std::move(placed));
    ctx.transaction_system.push("Place geometry", std::move(transaction));
    return;
  }

  if (entity_to_place)
  {

    entities::Entity* clone = entities::clone_entity(entity_to_place.get());
    if (clone == nullptr)
    {
      log_error("got a nullptr entity to place."); return;
    }

    std::shared_ptr<entities::Entity> new_entity(clone, &entities::destroy_entity);

    new_entity->position = compute_placement_origin(new_entity.get(), ghost_position);
 
    {
      auto uid = ctx.map->add_entity(new_entity);
      transaction_t transaction;
      transaction.add_created(uid, snapshot_entity(new_entity.get()));
      ctx.transaction_system.push(std::format("Place {}", entities::entity_info(new_entity->type).classname), std::move(transaction));
    }
  }
}

