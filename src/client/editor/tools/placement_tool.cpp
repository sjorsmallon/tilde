static shared::mesh_geometry_t make_placement_prototype(placeable_geometry_t geometry)
{
  const linalg::vec3 default_extents{editor::DEFAULT_HALF_EXTENT,
                                     editor::DEFAULT_HALF_EXTENT,
                                     editor::DEFAULT_HALF_EXTENT};

  switch (geometry)
  {
    case placeable_geometry_t::Asset_Mesh:
    {
      shared::mesh_geometry_t mesh;
      // placeholder mesh.
      mesh.source = shared::asset_mesh_source_t{"resources/obj/Error.obj", {1.f, 1.f, 1.f}};
      return mesh;
    }

    case placeable_geometry_t::Box:
      return shared::make_box_mesh({0, 0, 0}, default_extents);
  }

  log_error("make_placement_prototype: unhandled placeable {} — using a box", (int)geometry);
  return shared::make_box_mesh({0, 0, 0}, default_extents);
}



void Placement_Tool::select_placeable(int index)
{
  if (index < 0 || index >= (int)placeables().size())
    return;

  selected_type_index = index;
  const placeable_t &placeable = placeables()[index];
  hud::set_announcement(placeable.label);

  // Engage exactly one regime.
  geometry_to_place.reset();
  entity_to_place.reset();

  if (placeable.is_geometry)
  {
    geometry_to_place = make_placement_prototype(placeable.geometry);
    return;
  }

  // Every field is already at its declared default -- including the per-use ones
  // like Trigger_Volume's 64-unit box, which used to be written here and
  // disagreed with entities.def's {1,1,1} for as long as it did.
  entity_to_place = shared::make_entity(placeable.entity_type);
  if (!entity_to_place)
    log_error("select_placeable: no entity registered for \"{}\"", placeable.label);

  if (entities::Weapon_Entity* weapon = entities::entity_as<entities::Weapon_Entity>(entity_to_place.get()))
    shared::write_weapon_kind_counts(*weapon);
}

void Placement_Tool::on_key_down(editor_context_t& ctx, const key_event_t& e)
{
  for (int idx = 0; idx < (int)placeables().size() && idx < 9; ++idx)
  {
    int key_index = static_cast<int>(input::key_t::Num_1) + idx;
    if (static_cast<int>(e.key) == key_index)
    {
      select_placeable(idx);
      return;
    }
  }
}

void Placement_Tool::on_draw_inspector(editor_context_t& ctx)
{
  // Geometry and entities in one list, separated so it's obvious which is
  // which — they behave differently once placed (undo flavor, save form).
  const auto &table = placeables();
  for (int idx = 0; idx < (int)table.size(); ++idx)
  {
    const placeable_t &entry = table[idx];
    if (idx > 0 && table[idx - 1].is_geometry && !entry.is_geometry)
      ImGui::Separator();

    if (ImGui::Selectable(entry.label, idx == selected_type_index))
      select_placeable(idx);
  }

  // Prefabs are files, not a kind: picking one hands the piece to the
  // Selection tool and the PASTE gesture places it (prefab_def.md step 5).
  // That is why they are listed apart from the placeables above rather than
  // appended to that table.
  ImGui::Separator();
  if (!prefab_names_have_been_scanned)
    rescan_prefabs();

  ImGui::TextUnformatted("Prefabs");
  ImGui::SameLine();
  if (ImGui::SmallButton("Refresh"))
    rescan_prefabs();

  if (prefab_names.empty())
  {
    ImGui::TextDisabled("none in %s/", shared::PREFAB_DIRECTORY);
  }
  for (const std::string &prefab : prefab_names)
  {
    if (!ImGui::Selectable(prefab.c_str()))
      continue;

    const std::string path =
        std::string(shared::PREFAB_DIRECTORY) + "/" + prefab + shared::PREFAB_EXTENSION;
    std::optional<shared::map_t> piece = shared::try_load_map(path);
    if (!piece)
    {
      log_error("placement tool: prefab \"{}\" could not be read", path);
      continue;
    }

    ctx.requested_paste            = std::move(*piece);
    ctx.requested_paste_group_name = prefab;
  }
}

void Placement_Tool::rescan_prefabs()
{
  prefab_names.clear();
  prefab_names_have_been_scanned = true;

  std::error_code            error;
  const std::filesystem::path directory{shared::PREFAB_DIRECTORY};
  if (!std::filesystem::exists(directory, error))
    return;

  for (const std::filesystem::directory_entry &entry :
       std::filesystem::directory_iterator(directory, error))
  {
    if (!entry.is_regular_file() || entry.path().extension() != shared::PREFAB_EXTENSION)
      continue;
    prefab_names.push_back(entry.path().stem().string());
  }

  std::sort(prefab_names.begin(), prefab_names.end());
}

void Placement_Tool::on_draw_overlay(editor_context_t& ctx,
                                     pass_builder_t &draws)
{
  if (!cursor_is_currently_over_surface)
    return;

  if (geometry_to_place)
  {
    const linalg::vec3 center =
        compute_geometry_placement_center(*geometry_to_place, ghost_position,
                                          ctx.grid ? ctx.grid->step() : 0.0f);
    draw_geometry_ghost(*geometry_to_place, draws, center);
    return;
  }

  if (entity_to_place)
  {
    // The ghost is drawn at the ORIGIN the entity would be placed at, so what
    // you see previews exactly what gets stored.
    const linalg::vec3 origin =
        compute_placement_origin(entity_to_place.get(), ghost_position);

    draw_entity_ghost(entity_to_place.get(), draws, origin, ctx.entity_draw_settings);
  }
}

